// Generates TypeScript types from the JSON Schemas exported by the Python domain
// (`schemas/`, produced by scripts/export_schemas.py). Never edit the output by hand.
import { compileFromFile } from "json-schema-to-typescript";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemasDir = resolve(here, "../../schemas");
const outDir = resolve(here, "../src/types/generated");

const targets = [
  ["engine_output.schema.json", "engine_output.ts"],
  ["engine_input.schema.json", "engine_input.ts"],
];

const banner =
  "/* eslint-disable */\n/**\n * GENERATED by web/scripts/gen-types.mjs from schemas/{{file}}.\n * Do not edit by hand: run `npm run gen:types`.\n */";

await mkdir(outDir, { recursive: true });
for (const [schema, out] of targets) {
  const ts = await compileFromFile(resolve(schemasDir, schema), {
    bannerComment: banner.replace("{{file}}", schema),
    additionalProperties: false,
    unreachableDefinitions: true,
    style: { singleQuote: false },
  });
  await writeFile(resolve(outDir, out), ts);
  console.log(`types: ${schema} -> src/types/generated/${out}`);
}
